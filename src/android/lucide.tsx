/* The Android build's stand-in for lucide-react (vite.config aliases it when
   VITE_NATIVE=1): every icon the app imports, drawn as Google's Material Symbols
   (Rounded) — the icons Pixel's own apps use — from a font bundled in the app.
   Same names and props as lucide, so no screen changes; strokeWidth is ignored
   (Material Symbols set their own weight), fill="currentColor" draws the filled
   version, as an active navigation item does. */
import type { CSSProperties } from 'react'
import './android.css'
import './ripple'

type IconProps = { size?: number | string; color?: string; strokeWidth?: number | string; fill?: string; style?: CSSProperties; className?: string }
export type LucideIcon = ((p: IconProps) => JSX.Element) & { displayName?: string }

function make(symbol: string, name: string): LucideIcon {
  const C = ({ size = 24, color, fill, style, className }: IconProps) => (
    <span aria-hidden="true" className={'msym' + (className ? ' ' + className : '')} data-fill={fill && fill !== 'none' ? '' : undefined}
      style={{ fontSize: size, width: size, height: size, color, ...style }}>{symbol}</span>
  )
  C.displayName = name
  return C
}

