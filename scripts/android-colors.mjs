// Material 3 colour roles for the Android app, from Splitlife's green — the same
// scheme Pixel's own apps derive from a wallpaper (Tonal Spot). Prints CSS custom
// properties for light and dark; scripts writes them into src/android/m3-colors.css.
import { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors } from '@material/material-color-utilities'
import { writeFileSync } from 'node:fs'

const seed = Hct.fromInt(argbFromHex('#16a974'))
const roles = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer', 'error', 'onError', 'errorContainer', 'onErrorContainer',
  'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant', 'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest', 'surfaceDim', 'surfaceBright', 'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface', 'inversePrimary', 'scrim', 'shadow']
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())
const block = (dark) => {
  const scheme = new SchemeTonalSpot(seed, dark, 0)
  return roles.map((r) => `  --md-${kebab(r)}: ${hexFromArgb(MaterialDynamicColors[r].getArgb(scheme))};`).join('\n')
}
const css = `/* Generated by scripts/android-colors.mjs — Material 3 roles from #16a974 (Tonal Spot). Do not edit by hand. */
:root[data-os=android] {
${block(false)}
}
:root[data-os=android][data-theme=dark] {
${block(true)}
}
`
writeFileSync('src/android/m3-colors.css', css)
